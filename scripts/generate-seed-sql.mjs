// One-off generator: turns the existing static data files into a SQL seed file
// so the Supabase tables start out with everything already on the site today.
// Usage: node scripts/generate-seed-sql.mjs > supabase/seed.sql
import { axes } from '../src/data/axes.js'
import { vehicles } from '../src/data/vehicles.js'
import { getImage } from '../src/data/images.js'
import { coordinates } from '../src/data/coordinates.js'

const esc = (value) => `'${String(value ?? '').replace(/'/g, "''")}'`
const num = (value) => (value === null || value === undefined ? 'null' : Number(value))
const nullableEsc = (value) => (value ? esc(value) : 'null')
const tagsArray = (tags) => `ARRAY[${(tags || []).map(esc).join(', ')}]::text[]`

const lines = []
lines.push('-- Generated by scripts/generate-seed-sql.mjs — run once after schema.sql, in the Supabase SQL editor.')
lines.push('-- Safe to re-run: it clears the three tables first.')
lines.push('truncate table sites, vehicles, axes cascade;')
lines.push('')

lines.push('insert into axes (key, road_fr, road_en, title_fr, title_en, pitch_fr, pitch_en, vehicle_hint_fr, vehicle_hint_en, accent, position) values')
lines.push(
  axes
    .map((axis, i) =>
      `  (${esc(axis.key)}, ${esc(axis.road.fr)}, ${esc(axis.road.en)}, ${esc(axis.title.fr)}, ${esc(axis.title.en)}, ${esc(axis.pitch.fr)}, ${esc(axis.pitch.en)}, ${esc(axis.vehicleHint.fr)}, ${esc(axis.vehicleHint.en)}, ${esc(axis.accent)}, ${i})`,
    )
    .join(',\n') + ';',
)
lines.push('')

lines.push('insert into sites (axis_key, name, badge_fr, badge_en, description_fr, description_en, tags, image_url, lat, lng, position) values')
const siteRows = []
axes.forEach((axis) => {
  axis.sites.forEach((site, i) => {
    const point = coordinates[site.imgKey]
    const image = getImage(site.imgKey, 1200)
    siteRows.push(
      `  (${esc(axis.key)}, ${esc(site.name)}, ${esc(site.badge.fr)}, ${esc(site.badge.en)}, ${esc(site.description.fr)}, ${esc(site.description.en)}, ${tagsArray(site.tags)}, ${nullableEsc(image)}, ${point ? num(point.lat) : 'null'}, ${point ? num(point.lng) : 'null'}, ${i})`,
    )
  })
})
lines.push(siteRows.join(',\n') + ';')
lines.push('')

lines.push('insert into vehicles (name, type_fr, type_en, seats, bags, terrain_fr, terrain_en, fuel_fr, fuel_en, rate, available, image_url, position) values')
lines.push(
  vehicles
    .map(
      (vehicle, i) =>
        `  (${esc(vehicle.name)}, ${esc(vehicle.type.fr)}, ${esc(vehicle.type.en)}, ${num(vehicle.seats)}, ${num(vehicle.bags)}, ${esc(vehicle.terrain.fr)}, ${esc(vehicle.terrain.en)}, ${esc(vehicle.fuel.fr)}, ${esc(vehicle.fuel.en)}, ${num(vehicle.rate)}, ${num(vehicle.available)}, ${nullableEsc(getImage(vehicle.imgKey, 1200))}, ${i})`,
    )
    .join(',\n') + ';',
)

console.log(lines.join('\n'))
